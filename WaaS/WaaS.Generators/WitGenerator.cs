using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace WaaS.Generators;

/// <summary>
///     Generates the WIT definition of each interface declared with ComponentInterfaceAttribute,
///     and applies it to the interface with ComponentWitDefinitionAttribute.
/// </summary>
[Generator(LanguageNames.CSharp)]
public class WitGenerator : IIncrementalGenerator
{
    private const string BindingNamespace = "WaaS.ComponentModel.Binding";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var source = context.SyntaxProvider.ForAttributeWithMetadataName(
            $"{BindingNamespace}.ComponentInterfaceAttribute",
            static (node, ct) => true,
            (context, ct) => context);

        context.RegisterSourceOutput(source, Emit);
    }

    private static void Emit(SourceProductionContext source, GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol { TypeKind: TypeKind.Interface } namedSymbol) return;
        if (namedSymbol.ContainingType != null) return;
        if (!TryGetInterfaceName(namedSymbol, out var package, out var interfaceName)) return;

        string definition;
        try
        {
            definition = new WitInterfaceWriter(namedSymbol, package).Write(interfaceName);
        }
        catch (WitGenerationException ex)
        {
            source.ReportDiagnostic(Diagnostic.Create(Diagnostics.WitGenerationDiagnostic,
                context.TargetNode.GetLocation(), ex.Message));
            return;
        }

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        var hasNamespace = !namedSymbol.ContainingNamespace.IsGlobalNamespace;
        if (hasNamespace) builder.AppendLine($"namespace {namedSymbol.ContainingNamespace}\n{{");
        builder.AppendLine(
            $"    [global::WaaS.ComponentModel.Binding.ComponentWitDefinition({ToLiteral(package)}, {ToLiteral(interfaceName)}, {ToLiteral(definition)})]");
        builder.AppendLine($"    partial interface {namedSymbol.Name} {{ }}");
        if (hasNamespace) builder.AppendLine("}");

        var identifier = namedSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat
            .WithGlobalNamespaceStyle(SymbolDisplayGlobalNamespaceStyle.Omitted)
            .WithGenericsOptions(SymbolDisplayGenericsOptions.None));
        source.AddSource($"{identifier}.Wit.g.cs", builder.ToString());
    }

    internal static bool TryGetInterfaceName(INamedTypeSymbol symbol, out string package, out string interfaceName)
    {
        package = "";
        interfaceName = "";
        var attr = symbol.GetAttributes().FirstOrDefault(a =>
            a.AttributeClass?.Matches($"{BindingNamespace}.ComponentInterfaceAttribute") ?? false);
        if (attr?.ConstructorArguments.FirstOrDefault().Value is not string name) return false;

        // "namespace:package/interface"
        var slash = name.LastIndexOf('/');
        if (slash < 0) return false;
        package = name.Substring(0, slash);
        interfaceName = name.Substring(slash + 1);
        return true;
    }

    private static string ToLiteral(string value)
    {
        return "@\"" + value.Replace("\"", "\"\"") + "\"";
    }
}

internal class WitGenerationException : Exception
{
    public WitGenerationException(string message) : base(message)
    {
    }
}

/// <summary>
///     Writes the WIT definition of an interface. The mapping between C# types and component types
///     must be kept consistent with ComponentBindingInstanceGenerator.
/// </summary>
internal class WitInterfaceWriter
{
    private readonly INamedTypeSymbol interfaceSymbol;
    private readonly string package;

    // types used from other interfaces: interface reference -> type names
    private readonly SortedDictionary<string, SortedSet<string>> uses = new(StringComparer.Ordinal);

    public WitInterfaceWriter(INamedTypeSymbol interfaceSymbol, string package)
    {
        this.interfaceSymbol = interfaceSymbol;
        this.package = package;
    }

    public string Write(string interfaceName)
    {
        var body = new StringBuilder();

        // resources
        foreach (var resource in interfaceSymbol.GetMembers().OfType<INamedTypeSymbol>())
        {
            var resourceName = GetResourceName(resource);
            if (resourceName == null) continue;
            WriteResource(body, resource, resourceName);
        }

        // value types
        foreach (var type in interfaceSymbol.GetMembers().OfType<INamedTypeSymbol>())
        {
            if (!IsValueTypeDefinition(type)) continue;
            WriteValueType(body, type);
        }

        // functions
        foreach (var member in GetApis(interfaceSymbol))
        {
            var name = Utils.ToComponentApiName(member.memberSymbol);
            body.AppendLine($"    {name}: {WriteFunctionSignature(member, false)};");
        }

        var builder = new StringBuilder();
        builder.AppendLine($"interface {interfaceName} {{");
        foreach (var pair in uses)
            builder.AppendLine($"    use {pair.Key}.{{{string.Join(", ", pair.Value)}}};");
        if (uses.Count > 0 && body.Length > 0) builder.AppendLine();
        builder.AppendLine(body.ToString().TrimEnd());
        builder.AppendLine("}");

        // the output must not depend on the platform running the generator
        return builder.ToString().Replace("\r\n", "\n");
    }

    private void WriteResource(StringBuilder body, INamedTypeSymbol resource, string resourceName)
    {
        var apis = GetApis(resource).ToArray();
        if (apis.Length == 0)
        {
            body.AppendLine($"    resource {resourceName};");
            body.AppendLine();
            return;
        }

        body.AppendLine($"    resource {resourceName} {{");
        foreach (var member in apis)
        {
            var apiName = Utils.ToComponentApiName(member.memberSymbol);
            if (apiName.StartsWith("[constructor]", StringComparison.Ordinal))
            {
                body.AppendLine($"        constructor({WriteParameters(member, false)});");
            }
            else if (apiName.StartsWith("[method]", StringComparison.Ordinal))
            {
                var name = apiName.Substring(apiName.IndexOf('.') + 1);
                body.AppendLine($"        {name}: {WriteFunctionSignature(member, true)};");
            }
            else if (apiName.StartsWith("[static]", StringComparison.Ordinal))
            {
                var name = apiName.Substring(apiName.IndexOf('.') + 1);
                body.AppendLine($"        {name}: static {WriteFunctionSignature(member, false)};");
            }
            else
            {
                throw new WitGenerationException(
                    $"The member {member.memberSymbol.Name} of the resource {resourceName} must be named \"[constructor]...\", \"[method]...\" or \"[static]...\".");
            }
        }

        body.AppendLine("    }");
        body.AppendLine();
    }

    private void WriteValueType(StringBuilder body, INamedTypeSymbol type)
    {
        var name = Utils.ToComponentName(type.Name);

        if (type.TypeKind is TypeKind.Enum)
        {
            var isFlags = type.GetAttributes().Any(a => a.AttributeClass?.Matches("System.FlagsAttribute") ?? false);
            var values = type.GetMembers().OfType<IFieldSymbol>().Where(f => f.IsConst && f.IsStatic)
                .Select(f => Utils.ToComponentName(f.Name));
            body.AppendLine($"    {(isFlags ? "flags" : "enum")} {name} {{");
            foreach (var value in values) body.AppendLine($"        {value},");
            body.AppendLine("    }");
            body.AppendLine();
            return;
        }

        if (HasAttribute(type, "ComponentRecordAttribute"))
        {
            body.AppendLine($"    record {name} {{");
            foreach (var member in type.GetRecordMembers())
                body.AppendLine($"        {Utils.ToComponentName(member.Name)}: {TypeOf(GetMemberType(member))},");
            body.AppendLine("    }");
            body.AppendLine();
            return;
        }

        // variant
        body.AppendLine($"    variant {name} {{");
        foreach (var member in type.GetVariantMembers())
        {
            var memberType = GetMemberType(member);
            if (memberType.TryGetNullableElement(out var elementType)) memberType = elementType!;
            if (memberType.NullableAnnotation is NullableAnnotation.Annotated)
                memberType = memberType.WithNullableAnnotation(NullableAnnotation.NotAnnotated);

            var caseName = Utils.ToComponentName(member.Name);
            body.AppendLine(memberType.Matches("WaaS.ComponentModel.Binding.None")
                ? $"        {caseName},"
                : $"        {caseName}({TypeOf(memberType)}),");
        }

        body.AppendLine("    }");
        body.AppendLine();
    }

    private string WriteFunctionSignature(ComponentApi member, bool isMethod)
    {
        var builder = new StringBuilder();
        builder.Append($"func({WriteParameters(member, isMethod)})");
        if (member.returnType != null) builder.Append($" -> {TypeOf(member.returnType)}");
        return builder.ToString();
    }

    private string WriteParameters(ComponentApi member, bool isMethod)
    {
        // the first parameter of a method is `self`
        var parameters = isMethod ? member.parameters.Skip(1) : member.parameters;
        return string.Join(", ",
            parameters.Select(p => $"{Utils.ToComponentName(p.Name)}: {TypeOf(p.Type)}"));
    }

    private string TypeOf(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol named)
        {
            if (named.IsGenericType)
            {
                var unbound = named.ConstructUnboundGenericType();

                if (unbound.Matches("System.Nullable`1") || unbound.Matches("WaaS.ComponentModel.Binding.Option`1"))
                    return $"option<{TypeOf(named.TypeArguments[0])}>";

                if (unbound.Matches("WaaS.ComponentModel.Binding.Result`2"))
                {
                    var ok = IsNone(named.TypeArguments[0]) ? "_" : TypeOf(named.TypeArguments[0]);
                    var error = IsNone(named.TypeArguments[1]) ? null : TypeOf(named.TypeArguments[1]);
                    if (error == null) return ok == "_" ? "result" : $"result<{ok}>";
                    return $"result<{ok}, {error}>";
                }

                if (unbound.Matches("System.ReadOnlyMemory`1"))
                    return $"list<{TypeOf(named.TypeArguments[0])}>";

                if (named.TypeArguments.Length == 1 && named.TypeArguments[0] is INamedTypeSymbol resourceType &&
                    GetResourceName(resourceType) is { } resourceName)
                {
                    var reference = ReferenceType(resourceType, resourceName);
                    if (unbound.Matches("WaaS.ComponentModel.Binding.Owned`1")) return reference;
                    if (unbound.Matches("WaaS.ComponentModel.Binding.Borrowed`1")) return $"borrow<{reference}>";
                }
            }

            if (named.NullableAnnotation == NullableAnnotation.Annotated && named.IsReferenceType)
                return $"option<{TypeOf(named.WithNullableAnnotation(NullableAnnotation.NotAnnotated))}>";

            if (named.IsTupleType)
                return $"tuple<{string.Join(", ", named.TupleElements.Select(e => TypeOf(e.Type)))}>";

            if (IsValueTypeDefinition(named)) return ReferenceType(named, Utils.ToComponentName(named.Name));

            var alias = named.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.Matches("WaaS.ComponentModel.Binding.ComponentAliasAttribute") ?? false);
            if (alias?.ConstructorArguments.FirstOrDefault().Value is ITypeSymbol target) return TypeOf(target);
        }

        var primitive = type.SpecialType switch
        {
            SpecialType.System_Boolean => "bool",
            SpecialType.System_SByte => "s8",
            SpecialType.System_Byte => "u8",
            SpecialType.System_Int16 => "s16",
            SpecialType.System_UInt16 => "u16",
            SpecialType.System_Int32 => "s32",
            SpecialType.System_UInt32 => "u32",
            SpecialType.System_Int64 => "s64",
            SpecialType.System_UInt64 => "u64",
            SpecialType.System_Single => "f32",
            SpecialType.System_Double => "f64",
            SpecialType.System_String => "string",
            _ => null
        };
        if (primitive != null) return primitive;

        if (type.Matches("WaaS.ComponentModel.Binding.ComponentChar")) return "char";

        throw new WitGenerationException(
            $"The type {type.ToDisplayString()} cannot be represented in WIT.");
    }

    /// <summary>
    ///     Returns the name used to refer to a type, adding a `use` when it is declared in another interface.
    /// </summary>
    private string ReferenceType(INamedTypeSymbol type, string name)
    {
        var owner = type.ContainingType;
        if (owner == null || SymbolEqualityComparer.Default.Equals(owner, interfaceSymbol)) return name;

        if (!WitGenerator.TryGetInterfaceName(owner, out var ownerPackage, out var ownerInterface))
            throw new WitGenerationException(
                $"The type {type.ToDisplayString()} is not declared in a component interface.");

        var reference = ownerPackage == package ? ownerInterface : $"{ownerPackage}/{ownerInterface}";
        if (!uses.TryGetValue(reference, out var names)) uses[reference] = names = new SortedSet<string>();
        names.Add(name);
        return name;
    }

    private static ITypeSymbol GetMemberType(ISymbol member)
    {
        return member switch
        {
            IPropertySymbol property => property.Type,
            IFieldSymbol field => field.Type,
            _ => throw new ArgumentOutOfRangeException(nameof(member))
        };
    }

    private static bool IsNone(ITypeSymbol type)
    {
        return type.Matches("WaaS.ComponentModel.Binding.None");
    }

    private static bool HasAttribute(ISymbol symbol, string name)
    {
        return symbol.GetAttributes().Any(a => a.AttributeClass?.Matches($"WaaS.ComponentModel.Binding.{name}") ?? false);
    }

    private static bool IsValueTypeDefinition(INamedTypeSymbol type)
    {
        if (type.IsGenericType) return false;
        return type.TypeKind is TypeKind.Enum || HasAttribute(type, "ComponentRecordAttribute") ||
               HasAttribute(type, "ComponentVariantAttribute");
    }

    private static string? GetResourceName(INamedTypeSymbol type)
    {
        if (type.TypeKind != TypeKind.Interface) return null;
        if (!type.AllInterfaces.Any(i => i.Matches("WaaS.ComponentModel.Binding.IResourceImpl"))) return null;
        var attr = type.GetAttributes().FirstOrDefault(a =>
            a.AttributeClass?.Matches("WaaS.ComponentModel.Binding.ComponentResourceAttribute") ?? false);
        return attr?.ConstructorArguments.FirstOrDefault().Value as string;
    }

    private static IEnumerable<ComponentApi> GetApis(INamedTypeSymbol symbol)
    {
        // same as the APIs bound by ComponentBindingInstanceGenerator
        return symbol.GetMembers().Where(member =>
                member is { DeclaredAccessibility: Accessibility.Public, IsAbstract: true, IsStatic: false } &&
                member.GetAttributes().Any(attr =>
                    attr.AttributeClass?.Matches("WaaS.ComponentModel.Binding.ComponentApiAttribute") ?? false) &&
                member is IMethodSymbol or IPropertySymbol &&
                member is not (IMethodSymbol and ({ IsGenericMethod: true } or
                    { MethodKind: MethodKind.PropertyGet or MethodKind.PropertySet })))
            .Select(member => new ComponentApi(member));
    }
}
