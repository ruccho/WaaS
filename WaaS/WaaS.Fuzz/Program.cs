using System.Diagnostics;
using ConsoleAppFramework;
using WaaS;
using WaaS.Models;
using WaaS.Runtime;
using ExecutionContext = WaaS.Runtime.ExecutionContext;
using ValueType = WaaS.ValueType;

await ConsoleApp.RunAsync(args, Commands.RunAsync);

internal static class Commands
{
    // the features supported by WaaS
    private static readonly string[] SmithOptions =
    [
        "--simd-enabled", "true", "--reference-types-enabled", "true", "--bulk-memory-enabled", "true",
        "--multi-value-enabled", "true", "--saturating-float-to-int-enabled", "true",
        "--sign-extension-ops-enabled", "true", "--relaxed-simd-enabled", "false", "--threads-enabled", "false",
        "--exceptions-enabled", "false", "--gc-enabled", "false", "--tail-call-enabled", "false",
        "--memory64-enabled", "false", "--extended-const-enabled", "false", "--custom-page-sizes-enabled", "false",
        "--wide-arithmetic-enabled", "false", "--max-memories", "1", "--max-imports", "0",
        "--ensure-termination", "--export-everything", "true"
    ];

    /// <summary>
    ///     Loads, instantiates and runs the modules generated by wasm-smith, and the modules with random bytes mutated.
    ///     Reports the exceptions that are not expected for the input: valid modules must be loaded, and invalid
    ///     modules must be rejected with InvalidModuleException or InvalidCodeException.
    /// </summary>
    /// <param name="count">-n, Number of the modules to generate.</param>
    /// <param name="mutations">-m, Number of the mutated modules to run for each generated module.</param>
    /// <param name="seed">-s, Seed of the random numbers.</param>
    /// <param name="wasmTools">Path to wasm-tools.</param>
    /// <param name="output">-o, Directory to save the inputs that caused the failures.</param>
    public static async Task<int> RunAsync(int count = 100, int mutations = 10, int seed = 0,
        string wasmTools = "wasm-tools", string? output = null)
    {
        var random = new Random(seed);
        var temp = Directory.CreateTempSubdirectory("waas-fuzz-");
        var summary = new Summary();

        try
        {
            var inputPath = Path.Combine(temp.FullName, "input.bin");
            var modulePath = Path.Combine(temp.FullName, "module.wasm");
            for (var i = 0; i < count; i++)
            {
                var input = new byte[random.Next(1, 16) * 1024];
                random.NextBytes(input);
                await File.WriteAllBytesAsync(inputPath, input);
                await GenerateAsync(wasmTools, inputPath, modulePath);
                var binary = await File.ReadAllBytesAsync(modulePath);

                Run($"module {i}", binary, false, random, summary, output);
                for (var m = 0; m < mutations; m++)
                    Run($"module {i}, mutation {m}", Mutate(binary, random), true, random, summary, output);
            }
        }
        finally
        {
            temp.Delete(true);
        }

        Console.WriteLine(
            $"valid modules: {summary.Valid}, rejected: {summary.Rejected}, traps: {summary.Traps}, calls: {summary.Calls}, failures: {summary.Failures}");
        return summary.Failures == 0 ? 0 : 1;
    }

    private static async Task GenerateAsync(string wasmTools, string inputPath, string modulePath)
    {
        var startInfo = new ProcessStartInfo(wasmTools) { RedirectStandardError = true };
        startInfo.ArgumentList.Add("smith");
        startInfo.ArgumentList.Add(inputPath);
        startInfo.ArgumentList.Add("-o");
        startInfo.ArgumentList.Add(modulePath);
        foreach (var option in SmithOptions) startInfo.ArgumentList.Add(option);

        using var process = Process.Start(startInfo)!;
        var error = await process.StandardError.ReadToEndAsync();
        await process.WaitForExitAsync();
        if (process.ExitCode != 0) throw new InvalidOperationException($"wasm-tools smith failed: {error}");
    }

    private static byte[] Mutate(byte[] binary, Random random)
    {
        var mutated = (byte[])binary.Clone();
        var numMutations = random.Next(1, 4);
        for (var i = 0; i < numMutations; i++)
        {
            // the preamble is kept
            var position = random.Next(8, mutated.Length);
            mutated[position] = random.Next(3) switch
            {
                0 => (byte)random.Next(256),
                1 => (byte)(mutated[position] ^ (1 << random.Next(8))),
                _ => (byte)(mutated[position] + 1)
            };
        }

        return mutated;
    }

    private static void Run(string name, byte[] binary, bool mayBeInvalid, Random random, Summary summary,
        string? output)
    {
        void Fail(string phase, Exception exception)
        {
            summary.Failures++;
            Console.WriteLine($"FAIL {name} ({phase}): {exception}");
            if (output == null) return;
            Directory.CreateDirectory(output);
            File.WriteAllBytes(Path.Combine(output, $"failure-{summary.Failures}.wasm"), binary);
        }

        Module module;
        try
        {
            module = Module.Create(binary);
        }
        catch (Exception exception) when (mayBeInvalid && exception is InvalidModuleException or InvalidCodeException)
        {
            summary.Rejected++;
            return;
        }
        catch (Exception exception)
        {
            Fail("load", exception);
            return;
        }

        Instance instance;
        try
        {
            instance = new Instance(module, new Imports());
        }
        catch (Exception exception) when (IsExpected(exception))
        {
            // a trap in the initialization or the start function, or a memory larger than WaaS supports
            summary.Traps++;
            return;
        }
        catch (Exception exception)
        {
            Fail("instantiation", exception);
            return;
        }

        summary.Valid++;

        foreach (var (exportName, item) in instance.ExportInstance.Items)
        {
            if (item is not IInvocableFunction function) continue;

            var parameterTypes = function.Type.ParameterTypes.Span;
            var parameters = new StackValueItem[parameterTypes.Length];
            for (var i = 0; i < parameters.Length; i++)
                parameters[i] = parameterTypes[i] switch
                {
                    ValueType.I32 => new StackValueItem((uint)random.Next()),
                    ValueType.I64 => new StackValueItem(random.NextInt64()),
                    ValueType.F32 => new StackValueItem(random.NextSingle()),
                    ValueType.F64 => new StackValueItem(random.NextDouble()),
                    ValueType.V128 => new StackValueItem(default(V128)),
                    var type => StackValueItem.FromReference(type, null)
                };

            try
            {
                summary.Calls++;
                // the modules terminate by themselves, and the fuel bounds the time
                using var context = new ExecutionContext { Fuel = 10_000_000 };
                context.Invoke(function, parameters);
                Span<StackValueItem> results = stackalloc StackValueItem[context.ResultLength];
                context.TakeResults(results);
            }
            catch (Exception exception) when (IsExpected(exception))
            {
                summary.Traps++;
            }
            catch (Exception exception)
            {
                Fail($"invocation of \"{exportName}\"", exception);
            }
        }
    }

    private static bool IsExpected(Exception? exception)
    {
        for (; exception != null; exception = exception.InnerException)
            if (exception is TrapException or FuelExhaustedException or NotSupportedException)
                return true;
        return false;
    }

    private sealed class Summary
    {
        public int Valid, Rejected, Traps, Calls, Failures;
    }
}
