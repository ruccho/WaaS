use proc_macro2::{Delimiter, Literal, Span, TokenStream, TokenTree};
use quote::{format_ident, quote};
use syn::parse::{Parse, ParseStream};
use syn::punctuated::Punctuated;
use syn::{FnArg, GenericArgument, Ident, ItemFn, LitStr, Pat, PathArguments, Token, Type, parse_macro_input};

/// WIT of `wukuro:core`, resolved when this crate is compiled so that scripts do not depend on the project layout.
const WUKURO_CORE_WIT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/wit/wukuro-core");

/// Prefix of the package of each entry point. An entry point `foo_bar` is exported as
/// `wukuro-entry:foo-bar/entry` with a function `run`.
const ENTRY_PACKAGE_PREFIX: &str = "wukuro-entry";

/// Package of the types of Wukuro, which is resolved from [`WUKURO_CORE_WIT`].
const WUKURO_CORE_PACKAGE: &str = "wukuro:core";

/// Marker of the input that `#[entry]` passes to the macros of argument types.
const ARGUMENT_TYPE_MARKER: &str = "__wukuro_entry";

enum ParameterKind {
    /// a type of `wukuro:core` or a primitive type, with its type in WIT
    Builtin(&'static str),
    /// `T` of `&ObjectOf<T>`
    Object(Type),
    /// a record or an enum defined in C#, resolved by the macro of the same name as the type
    Argument,
}

struct Parameter {
    name: Ident,
    wit_name: String,
    ty: Type,
    kind: ParameterKind,
}

/// A record or an enum defined in C#, given by the macro generated for the type
/// (`WukuroArgumentTypeExporter.GenerateRust`).
struct ArgumentType {
    /// WIT package of the type, such as `my-game:events`
    package: String,
    /// WIT interface of the type in the package, such as `types`
    interface: String,
    /// name of the type in WIT, such as `door-settings`
    name: String,
    /// path of the Rust module that has the bindings of the interface
    module: TokenStream,
    /// WIT items of the interface that the type depends on, including the type itself
    items: Vec<String>,
}

impl Parse for ArgumentType {
    fn parse(input: ParseStream) -> syn::Result<Self> {
        let package = input.parse::<LitStr>()?.value();
        input.parse::<Token![,]>()?;
        let interface = input.parse::<LitStr>()?.value();
        input.parse::<Token![,]>()?;
        let name = input.parse::<LitStr>()?.value();
        input.parse::<Token![,]>()?;
        let module;
        syn::parenthesized!(module in input);
        let module = module.parse::<TokenStream>()?;
        input.parse::<Token![,]>()?;
        let items;
        syn::bracketed!(items in input);
        let items = Punctuated::<LitStr, Token![,]>::parse_terminated(&items)?
            .into_iter()
            .map(|item| item.value())
            .collect();
        if input.peek(Token![,]) {
            input.parse::<Token![,]>()?;
        }
        Ok(Self { package, interface, name, module, items })
    }
}

/// Exports the function as an entry point of the script.
/// A script file can have multiple entry points, which share the items in the file.
///
/// Parameters can be `&Context`, primitive types, `String`, `&Action`, `&Object`, `&ObjectOf<T>`, and records and
/// enums defined in C# whose Rust code is generated by `WukuroArgumentTypeExporter`.
/// For `&ObjectOf<T>`, the type name of `T` is recorded in the custom section `wukuro-entry-types`
/// so that the inspector accepts only objects of the type.
/// Their values are given by the arguments set to the script reference in the inspector,
/// matched by the parameter name.
#[proc_macro_attribute]
pub fn entry(
    _attr: proc_macro::TokenStream,
    item: proc_macro::TokenStream,
) -> proc_macro::TokenStream {
    let func = parse_macro_input!(item as ItemFn);
    let result = parse_parameters(&func).and_then(|params| {
        let argument_types = params
            .iter()
            .filter(|p| matches!(p.kind, ParameterKind::Argument))
            .map(|p| argument_type_path(&p.ty))
            .collect::<syn::Result<Vec<_>>>()?;
        if argument_types.is_empty() {
            return expand_entry(&func, params, Vec::new());
        }

        // the argument types are resolved one by one by the macros of the same names as the types, each of which
        // calls `resume_entry` with the definition of the type
        Ok(resolve_next(&argument_types, &[], &quote!(#func)))
    });
    match result {
        Ok(stream) => stream.into(),
        Err(error) => {
            let error = error.to_compile_error();
            quote!(#func #error).into()
        }
    }
}

/// Continues `#[entry]` after the macro of an argument type gives the definition of the type.
///
/// The input is `{ <definition> } [ <(path) of the types to resolve> ] [ <{ definition } of the resolved types> ] <fn>`.
#[doc(hidden)]
#[proc_macro]
pub fn __resume_entry(input: proc_macro::TokenStream) -> proc_macro::TokenStream {
    let input = TokenStream::from(input);
    match resume_entry(input) {
        Ok(stream) => stream.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

fn resume_entry(input: TokenStream) -> syn::Result<TokenStream> {
    let mut tokens = input.into_iter();
    let mut group = |delimiter: Delimiter, what: &str| match tokens.next() {
        Some(TokenTree::Group(group)) if group.delimiter() == delimiter => Ok(group),
        other => Err(syn::Error::new(
            other.map_or_else(Span::call_site, |t| t.span()),
            format!("expected {what} in the input of the entry point"),
        )),
    };
    let definition = group(Delimiter::Brace, "the definition of an argument type")?;
    let pending = group(Delimiter::Bracket, "the argument types to resolve")?;
    let resolved = group(Delimiter::Bracket, "the resolved argument types")?;
    let func = tokens.collect::<TokenStream>();

    let mut resolved = resolved.stream().into_iter().collect::<Vec<_>>();
    resolved.push(TokenTree::Group(definition));

    let pending = pending
        .stream()
        .into_iter()
        .filter_map(|t| match t {
            TokenTree::Group(group) if group.delimiter() == Delimiter::Parenthesis => Some(group.stream()),
            _ => None,
        })
        .collect::<Vec<_>>();
    if !pending.is_empty() {
        return Ok(resolve_next(&pending, &resolved, &func));
    }

    let argument_types = resolved
        .into_iter()
        .map(|t| match t {
            TokenTree::Group(group) => syn::parse2::<ArgumentType>(group.stream()),
            other => Err(syn::Error::new(other.span(), "expected the definition of an argument type")),
        })
        .collect::<syn::Result<Vec<_>>>()?;
    let func = syn::parse2::<ItemFn>(func)?;
    let params = parse_parameters(&func)?;
    expand_entry(&func, params, argument_types)
}

/// Calls the macro of the first type in `pending`, which calls `resume_entry` with the definition of the type.
fn resolve_next(pending: &[TokenStream], resolved: &[TokenTree], func: &TokenStream) -> TokenStream {
    let marker = Ident::new(ARGUMENT_TYPE_MARKER, Span::call_site());
    let next = &pending[0];
    let rest = pending[1..].iter().map(|path| quote!((#path)));
    quote! {
        #next! { @#marker [#(#rest)*] [#(#resolved)*] #func }
    }
}

fn argument_type_path(ty: &Type) -> syn::Result<TokenStream> {
    match ty {
        Type::Path(path) if path.qself.is_none() && path.path.segments.iter().all(|s| s.arguments.is_none()) => {
            Ok(quote!(#path))
        }
        _ => Err(syn::Error::new_spanned(ty, "this type cannot be a parameter of an entry point")),
    }
}

fn parse_parameters(func: &ItemFn) -> syn::Result<Vec<Parameter>> {
    let mut params = Vec::<Parameter>::new();
    for arg in &func.sig.inputs {
        let FnArg::Typed(pat_type) = arg else {
            return Err(syn::Error::new_spanned(arg, "entry points cannot take self"));
        };
        let Pat::Ident(pat_ident) = &*pat_type.pat else {
            return Err(syn::Error::new_spanned(&pat_type.pat, "parameters must be identifiers"));
        };
        let ty = (*pat_type.ty).clone();
        let kind = if let Some(object_type) = to_object_type(&ty) {
            ParameterKind::Object(object_type)
        } else if let Some(wit_type) = to_wit_type(&ty) {
            ParameterKind::Builtin(wit_type)
        } else if matches!(ty, Type::Path(_)) {
            ParameterKind::Argument
        } else {
            return Err(syn::Error::new_spanned(&ty, "this type cannot be a parameter of an entry point"));
        };
        params.push(Parameter {
            name: pat_ident.ident.clone(),
            wit_name: to_kebab_case(&pat_ident.ident.to_string()),
            ty,
            kind,
        });
    }
    Ok(params)
}

fn expand_entry(func: &ItemFn, params: Vec<Parameter>, argument_types: Vec<ArgumentType>) -> syn::Result<TokenStream> {
    let fn_name = &func.sig.ident;
    let entry_name = to_kebab_case(&fn_name.to_string());
    let package = format!("{ENTRY_PACKAGE_PREFIX}:{entry_name}");

    // the argument types are given in the order of the parameters
    let mut argument_types = argument_types.into_iter();
    let mut wit_params = Vec::new();
    let mut parameter_types = Vec::new();
    for param in &params {
        let wit_type = match &param.kind {
            ParameterKind::Builtin(wit_type) => wit_type.to_string(),
            ParameterKind::Object(_) => "borrow<object>".to_string(),
            ParameterKind::Argument => {
                let argument_type = argument_types
                    .next()
                    .ok_or_else(|| syn::Error::new_spanned(&param.ty, "the definition of the type is not given"))?;
                let wit_type = argument_type.name.clone();
                parameter_types.push(argument_type);
                wit_type
            }
        };
        wit_params.push(format!("{}: {}", param.wit_name, wit_type));
    }

    // the interfaces of the argument types: (package, interface) -> (module, names, items)
    let mut interfaces = Vec::<(String, String, TokenStream, Vec<String>, Vec<String>)>::new();
    for argument_type in parameter_types {
        let index = match interfaces
            .iter()
            .position(|i| i.0 == argument_type.package && i.1 == argument_type.interface)
        {
            Some(index) => index,
            None => {
                interfaces.push((
                    argument_type.package.clone(),
                    argument_type.interface.clone(),
                    argument_type.module.clone(),
                    Vec::new(),
                    Vec::new(),
                ));
                interfaces.len() - 1
            }
        };
        let (_, _, _, names, items) = &mut interfaces[index];
        if !names.contains(&argument_type.name) {
            names.push(argument_type.name);
        }
        for item in argument_type.items {
            if !items.contains(&item) {
                items.push(item);
            }
        }
    }

    let uses = interfaces
        .iter()
        .map(|(package, interface, _, names, _)| {
            format!("    use {package}/{interface}.{{{}}};\n", names.join(", "))
        })
        .collect::<String>();

    // the types are defined in the WIT of the entry point, since the WIT of the crate that has the bindings of
    // the types cannot be located from here
    let mut packages = Vec::<(String, String)>::new();
    for (package, interface, _, _, items) in &interfaces {
        if package == WUKURO_CORE_PACKAGE {
            continue;
        }
        let body = items
            .iter()
            .map(|item| indent(item, "        "))
            .collect::<Vec<_>>()
            .join("\n");
        let definition = format!("    interface {interface} {{\n{body}\n    }}\n");
        match packages.iter_mut().find(|p| &p.0 == package) {
            Some(p) => p.1.push_str(&definition),
            None => packages.push((package.clone(), definition)),
        }
    }
    let nested_packages = packages
        .iter()
        .map(|(package, definitions)| format!("\npackage {package} {{\n{definitions}}}\n"))
        .collect::<String>();

    let wit = format!(
        r#"
        package {package};

        world entry-world {{
            export entry;
        }}

        interface entry {{
            use wukuro:core/types.{{context, action, object}};
{uses}
            run: func({});
        }}
{nested_packages}"#,
        wit_params.join(", ")
    );
    let wit = Literal::string(&wit);
    let world = Literal::string(&format!("{package}/entry-world"));
    let core_wit = Literal::string(WUKURO_CORE_WIT);

    // the bindings of the argument types are the types in the crate that defines them
    let mut with_imports = Vec::new();
    let mut with_entries = Vec::new();
    for (index, (package, interface, module, _, _)) in interfaces.iter().enumerate() {
        if package == WUKURO_CORE_PACKAGE {
            continue;
        }
        let alias = format_ident!("__wukuro_with_{}", index);
        with_imports.push(quote!(use #module as #alias;));
        let key = Literal::string(&format!("{package}/{interface}"));
        with_entries.push(quote!(#key: #alias,));
    }

    let module = format_ident!("__wukuro_entry_{}", fn_name);
    let package_module = Ident::new(&entry_name.replace('-', "_"), Span::call_site());
    let param_pats = params.iter().map(|p| {
        let name = &p.name;
        let ty = &p.ty;
        match &p.kind {
            ParameterKind::Object(_) => quote!(#name: &::wukuro::types::Object),
            _ => quote!(#name: #ty),
        }
    });
    let param_args = params.iter().map(|p| {
        let name = &p.name;
        match &p.kind {
            ParameterKind::Object(_) => quote!(::wukuro::ObjectOf::from_ref(#name)),
            _ => quote!(#name),
        }
    });

    // records of the object types of the parameters, read by the inspector
    let records = params.iter().filter_map(|p| {
        let ParameterKind::Object(object_type) = &p.kind else { return None };
        let entry = Literal::string(&entry_name);
        let parameter = Literal::string(&p.wit_name);
        let name = format_ident!("__WUKURO_ENTRY_TYPE_{}", p.name.to_string().to_uppercase());
        Some(quote! {
            #[used]
            #[unsafe(link_section = "wukuro-entry-types")]
            static #name: [u8; ::wukuro::__private::record_len(
                #entry, #parameter, <#object_type as ::wukuro::ObjectType>::TYPE_NAME)] =
                ::wukuro::__private::record(#entry, #parameter, <#object_type as ::wukuro::ObjectType>::TYPE_NAME);
        })
    });

    Ok(quote! {
        #func

        #[doc(hidden)]
        #[allow(non_snake_case, unused_imports)]
        mod #module {
            // the parameter types are written in the scope of the script
            use super::*;

            #(#with_imports)*

            ::wit_bindgen::generate!({
                inline: #wit,
                path: #core_wit,
                with: {
                    "wukuro:core/types": ::wukuro::wukuro::core::types,
                    #(#with_entries)*
                },
                world: #world,
            });

            struct Entry;

            impl exports::wukuro_entry::#package_module::entry::Guest for Entry {
                fn run(#(#param_pats),*) {
                    ::wukuro::__private::install_panic_hook();
                    super::#fn_name(#(#param_args),*);
                }
            }

            export!(Entry);

            #(#records)*
        }
    })
}

fn indent(text: &str, prefix: &str) -> String {
    text.lines()
        .map(|line| if line.is_empty() { String::new() } else { format!("{prefix}{line}") })
        .collect::<Vec<_>>()
        .join("\n")
}

fn to_wit_type(ty: &Type) -> Option<&'static str> {
    let (is_reference, path) = match ty {
        Type::Reference(r) => match &*r.elem {
            Type::Path(path) => (true, path),
            _ => return None,
        },
        Type::Path(path) => (false, path),
        _ => return None,
    };
    let name = path.path.segments.last()?.ident.to_string();
    Some(match (is_reference, name.as_str()) {
        (true, "Context") => "borrow<context>",
        (true, "Action") => "borrow<action>",
        (true, "Object") => "borrow<object>",
        (false, "bool") => "bool",
        (false, "i8") => "s8",
        (false, "i16") => "s16",
        (false, "i32") => "s32",
        (false, "i64") => "s64",
        (false, "u8") => "u8",
        (false, "u16") => "u16",
        (false, "u32") => "u32",
        (false, "u64") => "u64",
        (false, "f32") => "f32",
        (false, "f64") => "f64",
        (false, "char") => "char",
        (false, "String") => "string",
        _ => return None,
    })
}

/// Returns `T` if the type is `&ObjectOf<T>`.
fn to_object_type(ty: &Type) -> Option<Type> {
    let Type::Reference(reference) = ty else { return None };
    let Type::Path(path) = &*reference.elem else { return None };
    let segment = path.path.segments.last()?;
    if segment.ident != "ObjectOf" {
        return None;
    }
    let PathArguments::AngleBracketed(arguments) = &segment.arguments else { return None };
    match arguments.args.first()? {
        GenericArgument::Type(object_type) => Some(object_type.clone()),
        _ => None,
    }
}

fn to_kebab_case(name: &str) -> String {
    name.trim_matches('_').replace('_', "-")
}
