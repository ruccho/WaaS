
pub use wukuro_macro::entry;

pub use wukuro::core::functions;
pub use wukuro::core::types;

use std::ops;

wit_bindgen::generate!({
    inline: r#"
        package wukuro:core-inline;

        world imports {
            import wukuro:core/functions;
            import wukuro:core/types;
        }
    "#,
    path: "wit/wukuro-core",
    generate_all
});


/// A type of Unity objects that can be passed to scripts. Implemented by marker types generated from C#
/// (`[assembly: WukuroObjectType(typeof(...))]`).
pub trait ObjectType {
    /// The assembly-qualified name of the C# type, such as `UnityEngine.Transform, UnityEngine.CoreModule`.
    const TYPE_NAME: &'static str;
}

/// An object of the type `T`. Use `&ObjectOf<T>` as a parameter of an entry point to let the inspector accept only
/// objects of the type. It dereferences to [`types::Object`] and can be passed to functions taking `&Object`.
#[repr(transparent)]
pub struct ObjectOf<T: ObjectType> {
    object: types::Object,
    _type: std::marker::PhantomData<T>,
}

impl<T: ObjectType> ObjectOf<T> {
    #[doc(hidden)]
    pub fn from_ref(object: &types::Object) -> &Self {
        // SAFETY: ObjectOf<T> is a transparent wrapper of Object
        unsafe { &*(object as *const types::Object as *const Self) }
    }
}

impl<T: ObjectType> ops::Deref for ObjectOf<T> {
    type Target = types::Object;

    fn deref(&self) -> &types::Object {
        &self.object
    }
}

/// Items used by the code generated by `#[entry]`.
#[doc(hidden)]
pub mod __private {
    /// Name of the custom section where `#[entry]` records the object types of the parameters.
    /// Each record is `<entry>\t<parameter>\t<type name>\n` with names in kebab-case.
    pub const ENTRY_TYPES_SECTION: &str = "wukuro-entry-types";

    pub const fn record_len(entry: &str, parameter: &str, type_name: &str) -> usize {
        entry.len() + parameter.len() + type_name.len() + 3
    }

    pub const fn record<const N: usize>(entry: &str, parameter: &str, type_name: &str) -> [u8; N] {
        let mut out = [0u8; N];
        let mut at = copy(&mut out, 0, entry.as_bytes());
        out[at] = b'\t';
        at = copy(&mut out, at + 1, parameter.as_bytes());
        out[at] = b'\t';
        at = copy(&mut out, at + 1, type_name.as_bytes());
        out[at] = b'\n';
        out
    }

    const fn copy<const N: usize>(out: &mut [u8; N], mut at: usize, source: &[u8]) -> usize {
        let mut i = 0;
        while i < source.len() {
            out[at] = source[i];
            at += 1;
            i += 1;
        }
        at
    }
}
