/// A value that can be shown to the player as a text: a string written directly in the script, or a localized text
/// created by [`l10n!`].
pub trait IntoText {
    fn into_text(self) -> types::Text;
}

impl IntoText for types::Text {
    fn into_text(self) -> types::Text {
        self
    }
}

impl IntoText for &types::Text {
    fn into_text(self) -> types::Text {
        self.clone()
    }
}

impl IntoText for &str {
    fn into_text(self) -> types::Text {
        types::Text::Plain(self.to_string())
    }
}

impl IntoText for &&str {
    fn into_text(self) -> types::Text {
        types::Text::Plain(self.to_string())
    }
}

impl IntoText for String {
    fn into_text(self) -> types::Text {
        types::Text::Plain(self)
    }
}

impl IntoText for &String {
    fn into_text(self) -> types::Text {
        types::Text::Plain(self.clone())
    }
}

/// Creates a reference to a localized text from a table name and a key.
///
/// The optional third argument is the source text at the time of localization. It is not used at runtime and is kept
/// only to make the script readable.
#[macro_export]
macro_rules! l10n {
    ($table:expr, $key:expr $(, $source:expr)? $(,)?) => {
        $crate::types::Text::Localized($crate::types::TextId {
            table: ::std::string::ToString::to_string($table),
            key: ::std::string::ToString::to_string($key),
        })
    };
}

/// A type of Unity objects that can be passed to scripts. Implemented by marker types generated from C#
/// (`[assembly: WukuroObjectType(typeof(...))]`).
pub trait ObjectType {
    /// The assembly-qualified name of the C# type, such as `UnityEngine.Transform, UnityEngine.CoreModule`.
    const TYPE_NAME: &'static str;
}

/// An object of the type `T`. Use `&ObjectOf<T>` as a parameter of an entry point to let the inspector accept only
/// objects of the type. It dereferences to [`types::Object`] and can be passed to functions taking `&Object`.
#[repr(transparent)]
pub struct ObjectOf<T: ObjectType> {
    object: types::Object,
    _type: std::marker::PhantomData<T>,
}

impl<T: ObjectType> ObjectOf<T> {
    #[doc(hidden)]
    pub fn from_ref(object: &types::Object) -> &Self {
        // SAFETY: ObjectOf<T> is a transparent wrapper of Object
        unsafe { &*(object as *const types::Object as *const Self) }
    }
}

impl<T: ObjectType> ops::Deref for ObjectOf<T> {
    type Target = types::Object;

    fn deref(&self) -> &types::Object {
        &self.object
    }
}

/// Items used by the code generated by `#[entry]`.
#[doc(hidden)]
pub mod __private {
    /// Name of the custom section where `#[entry]` records the object types of the parameters.
    /// Each record is `<entry>\t<parameter>\t<type name>\n` with names in kebab-case.
    pub const ENTRY_TYPES_SECTION: &str = "wukuro-entry-types";

    /// Installs a panic hook that reports the panic message and its location to the host.
    /// Called by every entry point before running the script. Only the first call installs the hook.
    ///
    /// Without the hook, the host sees only the `unreachable` instruction executed after a panic.
    pub fn install_panic_hook() {
        static INSTALL: std::sync::Once = std::sync::Once::new();
        INSTALL.call_once(|| {
            std::panic::set_hook(Box::new(|info| {
                // e.g. "panicked at src/lib.rs:10:5:\nmessage"
                let message = info.to_string();
                // the host aborts the execution, so this does not return normally
                crate::functions::panic(&message);
            }));
        });
    }

    pub const fn record_len(entry: &str, parameter: &str, type_name: &str) -> usize {
        entry.len() + parameter.len() + type_name.len() + 3
    }

    pub const fn record<const N: usize>(entry: &str, parameter: &str, type_name: &str) -> [u8; N] {
        let mut out = [0u8; N];
        let mut at = copy(&mut out, 0, entry.as_bytes());
        out[at] = b'\t';
        at = copy(&mut out, at + 1, parameter.as_bytes());
        out[at] = b'\t';
        at = copy(&mut out, at + 1, type_name.as_bytes());
        out[at] = b'\n';
        out
    }

    const fn copy<const N: usize>(out: &mut [u8; N], mut at: usize, source: &[u8]) -> usize {
        let mut i = 0;
        while i < source.len() {
            out[at] = source[i];
            at += 1;
            i += 1;
        }
        at
    }
}
