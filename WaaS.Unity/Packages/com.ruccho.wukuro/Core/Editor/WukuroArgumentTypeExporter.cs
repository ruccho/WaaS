using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using System.Text;
using WaaS.ComponentModel.Binding;
using Wukuro.Core;

namespace Wukuro.Editor
{
    /// <summary>
    ///     Generates the Rust code that lets records and enums defined in C# (<see cref="WukuroArgumentTypes" />) be
    ///     parameters of entry points (<c>#[entry]</c>).
    /// </summary>
    /// <remarks>
    ///     For each type, a macro of the same name as the type is generated. <c>#[entry]</c> calls the macro to get the
    ///     definition of the type in WIT and the module of its bindings, since a procedural macro cannot read the
    ///     definitions of other crates. The generated file is a module whose items are re-exported from the module that
    ///     has the bindings of the interface (generated by wit-bindgen), so that importing a type also imports the macro.
    ///     It must not be included with <c>include!</c>, since the macros are exported with <c>#[macro_export]</c>.
    /// </remarks>
    public static class WukuroArgumentTypeExporter
    {
        private const string MacroPrefix = "__wukuro_argument_type_";

        /// <summary>
        ///     The argument types declared in the interface with <see cref="ComponentInterfaceAttribute" />, ordered by
        ///     the name.
        /// </summary>
        public static IReadOnlyList<Type> CollectTypes(Type componentInterface)
        {
            return componentInterface.GetNestedTypes()
                .Where(WukuroArgumentTypes.IsArgumentType)
                .OrderBy(WukuroArgumentTypes.GetWitName, StringComparer.Ordinal)
                .ToArray();
        }

        /// <summary>
        ///     Generates the macros of the argument types declared in the interface.
        /// </summary>
        /// <param name="componentInterface">C# interface with <see cref="ComponentInterfaceAttribute" />.</param>
        /// <param name="modulePath">
        ///     Path of the Rust module that has the bindings of the interface, from the root of the crate, such as
        ///     <c>types</c> for <c>my_game::types</c>.
        /// </param>
        /// <param name="header">Text written at the beginning, such as a comment.</param>
        public static string GenerateRust(Type componentInterface, string modulePath, string header)
        {
            var interfaceName = componentInterface.GetCustomAttribute<ComponentInterfaceAttribute>()?.Name ??
                                throw new ArgumentException(
                                    $"{componentInterface.FullName} has no ComponentInterface attribute.",
                                    nameof(componentInterface));
            var slash = interfaceName.LastIndexOf('/');
            var package = interfaceName.Substring(0, slash);
            var @interface = interfaceName.Substring(slash + 1);
            var module = string.IsNullOrEmpty(modulePath) ? "$crate" : $"$crate::{modulePath}";

            var builder = new StringBuilder(header);
            foreach (var type in CollectTypes(componentInterface))
            {
                var witName = WukuroArgumentTypes.GetWitName(type);
                var macro = MacroPrefix + ToSnakeCase($"{package}-{@interface}-{witName}");

                builder.Append('\n');
                builder.Append($"/// `{type.FullName?.Replace('+', '.')}`\n");
                builder.Append("#[doc(hidden)]\n#[macro_export]\n");
                builder.Append($"macro_rules! {macro} {{\n");
                builder.Append("    (@__wukuro_entry $($input:tt)*) => {\n");
                builder.Append("        ::wukuro::__private::resume_entry! {\n");
                builder.Append("            {\n");
                builder.Append(
                    $"                {ToRustString(package)}, {ToRustString(@interface)}, {ToRustString(witName)}, ({module}),\n");
                builder.Append("                [\n");
                foreach (var item in GetWitItems(type))
                    builder.Append($"                    {ToRustString(item)},\n");
                builder.Append("                ]\n");
                builder.Append("            }\n");
                builder.Append("            $($input)*\n");
                builder.Append("        }\n");
                builder.Append("    };\n");
                builder.Append("}\n\n");
                builder.Append("#[doc(hidden)]\n");
                builder.Append($"pub use crate::{macro} as {ToUpperCamelCase(witName)};\n");
            }

            return builder.ToString();
        }

        /// <summary>
        ///     The WIT items of the interface that the type depends on, including the type itself and a <c>use</c> of
        ///     <c>wukuro:core/types</c> if needed. The types must be declared in the same interface.
        /// </summary>
        public static IReadOnlyList<string> GetWitItems(Type type)
        {
            var visited = new HashSet<Type>();
            var items = new List<string>();
            var usesObject = false;

            void Visit(Type current)
            {
                if (!visited.Add(current)) return;
                if (WukuroArgumentTypes.GetInterfaceName(current) != WukuroArgumentTypes.GetInterfaceName(type))
                    throw new NotSupportedException(
                        $"{current.FullName} is used by {type.FullName} but declared in another interface.");

                var builder = new StringBuilder();
                var name = WukuroArgumentTypes.GetWitName(current);
                if (current.IsEnum)
                {
                    var isFlags = current.IsDefined(typeof(FlagsAttribute), false);
                    builder.Append($"{(isFlags ? "flags" : "enum")} {name} {{\n");
                    foreach (var value in current.GetFields(BindingFlags.Public | BindingFlags.Static)
                                 .OrderBy(f => f.MetadataToken))
                        builder.Append($"    {WukuroArgumentTypes.ToComponentName(value.Name)},\n");
                    builder.Append('}');
                }
                else
                {
                    var fields = new List<string>();
                    foreach (var field in WukuroArgumentTypes.GetFields(current))
                    {
                        var fieldType = WukuroArgumentTypes.GetFieldType(field);
                        string witType;
                        if (IsObject(fieldType))
                        {
                            usesObject = true;
                            witType = "object";
                        }
                        else if (WukuroArgumentTypes.IsArgumentType(fieldType))
                        {
                            Visit(fieldType);
                            witType = WukuroArgumentTypes.GetWitName(fieldType);
                        }
                        else
                        {
                            witType = GetPrimitiveWitType(fieldType) ?? throw new NotSupportedException(
                                $"The type {fieldType.Name} of the field {field.Name} of {current.FullName} cannot be a field of an argument type.");
                        }

                        fields.Add($"    {WukuroArgumentTypes.ToComponentName(field.Name)}: {witType},\n");
                    }

                    builder.Append($"record {name} {{\n");
                    foreach (var field in fields) builder.Append(field);
                    builder.Append('}');
                }

                items.Add(builder.ToString());
            }

            Visit(type);
            if (usesObject) items.Insert(0, "use wukuro:core/types.{object};");
            return items;
        }

        /// <summary>
        ///     Whether the type is a reference to a Unity object in a record, which is the <c>object</c> resource of
        ///     <c>wukuro:core</c> in WIT.
        /// </summary>
        public static bool IsObject(Type type)
        {
            return type == typeof(Owned<ITypes.IObjectResourceImpl>) ||
                   type.IsGenericType && type.GetGenericTypeDefinition() == typeof(ObjectOf<>);
        }

        /// <summary>
        ///     The WIT type of a primitive type or string, or null.
        /// </summary>
        public static string GetPrimitiveWitType(Type type)
        {
            if (type == typeof(bool)) return "bool";
            if (type == typeof(sbyte)) return "s8";
            if (type == typeof(byte)) return "u8";
            if (type == typeof(short)) return "s16";
            if (type == typeof(ushort)) return "u16";
            if (type == typeof(int)) return "s32";
            if (type == typeof(uint)) return "u32";
            if (type == typeof(long)) return "s64";
            if (type == typeof(ulong)) return "u64";
            if (type == typeof(float)) return "f32";
            if (type == typeof(double)) return "f64";
            if (type == typeof(string)) return "string";
            if (type == typeof(WaaS.ComponentModel.Binding.ComponentChar)) return "char";
            return null;
        }

        /// <summary>
        ///     The name of a type in the bindings generated by wit-bindgen, such as "DoorSettings" for "door-settings".
        /// </summary>
        public static string ToUpperCamelCase(string witName)
        {
            return string.Concat(witName.Split('-').Where(w => w.Length > 0)
                .Select(w => char.ToUpperInvariant(w[0]) + w.Substring(1)));
        }

        private static string ToSnakeCase(string name)
        {
            return new string(name.Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());
        }

        private static string ToRustString(string value)
        {
            return "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\"";
        }
    }
}
