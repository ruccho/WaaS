#nullable enable
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using WaaS.Unity.Editor;
using WaaS.Unity.Editor.MoonBit;

namespace Wukuro.Editor
{
    /// <summary>
    ///     Exports the functions with the attribute <c>#wukuro.entry</c> of a MoonBit script as entry points, as
    ///     <c>#[entry]</c> of the Rust crate does. Set to the generators of the MoonBit importer.
    /// </summary>
    /// <remarks>
    ///     An entry point <c>foo_bar</c> is exported as the interface <c>wukuro-entry:foo-bar/entry</c> with a function
    ///     <c>run</c>. The parameters can be <c>Context</c>, primitive types, <c>String</c>, <c>Action</c>, <c>Object</c>
    ///     and <c>ObjectOf[T]</c> of the package <c>ruccho/wukuro</c>. The type of an object of <c>ObjectOf[T]</c> is
    ///     declared by the attribute <c>#wukuro.object_type("&lt;C# type name&gt;")</c> of the marker type <c>T</c>.
    /// </remarks>
    [Serializable]
    [ManagedReferenceTypeDisplayName("Wukuro Entry Points")]
    public class WukuroMoonBitEntryGenerator : IMoonBitGenerator
    {
        private const string LibraryPackage = "ruccho/wukuro";
        private const string CoreTypesPackage = "ruccho/wukuro/bindings/wukuro_core_types";

        // at most 16 flat values are passed to a function as its parameters by the canonical ABI
        private const int MaxFlatParams = 16;

        private static readonly Regex EntryRegex = new(
            @"#wukuro\.entry\b[^\n]*\n(?:[ \t]*(?:#|///)[^\n]*\n)*[ \t]*(?<pub>pub\s+)?fn\s+(?<name>[A-Za-z_][A-Za-z0-9_]*)\s*\((?<params>[^)]*)\)",
            RegexOptions.Compiled);

        private static readonly Regex InterfaceFunctionRegex = new(
            @"^pub fn (?<name>[A-Za-z_][A-Za-z0-9_]*)\((?<params>.*)\) -> (?<result>.+)$",
            RegexOptions.Compiled | RegexOptions.Multiline);

        private static readonly Regex InterfaceImportRegex = new(
            @"^\s*""(?<path>[^""]+)""(?:\s*@(?<alias>[A-Za-z_][A-Za-z0-9_]*))?\s*,?\s*$",
            RegexOptions.Compiled | RegexOptions.Multiline);

        public void Generate(MoonBitGenerationContext context)
        {
            var functions = InterfaceFunctionRegex.Matches(context.ScriptInterface).Cast<Match>()
                .ToDictionary(m => m.Groups["name"].Value, m => m);
            var aliases = ParseImports(context.ScriptInterface);

            var glue = new StringBuilder("// Generated by Wukuro. DO NOT EDIT!\n");
            var objectTypes = new StringBuilder();
            var entryNames = new HashSet<string>();

            foreach (Match entry in EntryRegex.Matches(context.Source))
            {
                var name = entry.Groups["name"].Value;
                if (!entry.Groups["pub"].Success)
                    throw new InvalidOperationException($"The entry point {name} must be public (pub fn).");
                if (!functions.TryGetValue(name, out var function))
                    throw new InvalidOperationException($"The entry point {name} is not found in the script.");
                if (function.Groups["result"].Value.Trim() != "Unit")
                    throw new InvalidOperationException($"The entry point {name} must return Unit.");

                var entryName = ToKebabCase(name);
                if (!entryNames.Add(entryName))
                    throw new InvalidOperationException($"The entry point {entryName} is duplicated.");

                var parameterNames = SplitTopLevel(entry.Groups["params"].Value)
                    .Select(p => p.Split(':')[0].Trim().TrimEnd('~', '?'))
                    .ToArray();
                var parameterTypes = SplitTopLevel(function.Groups["params"].Value).ToArray();
                if (parameterNames.Length != parameterTypes.Length)
                    throw new InvalidOperationException($"The parameters of the entry point {name} are not recognized.");

                var witParameters = new List<string>();
                var flatParameters = new List<string>();
                var arguments = new List<string>();
                for (var i = 0; i < parameterTypes.Length; i++)
                {
                    var parameterName = ToKebabCase(parameterNames[i]);
                    var type = ResolveType(parameterTypes[i], aliases);
                    var parameter = MapParameter(type, flatParameters, out var witType, out var objectType,
                        context.SourceDirectories)
                        ?? throw new InvalidOperationException(
                            $"The type {parameterTypes[i]} of the parameter {parameterNames[i]} of the entry point {name} cannot be a parameter of an entry point.");
                    witParameters.Add($"{parameterName}: {witType}");
                    arguments.Add(parameter);
                    if (objectType != null) objectTypes.Append($"{entryName}\t{parameterName}\t{objectType}\n");
                }

                if (flatParameters.Count > MaxFlatParams)
                    throw new InvalidOperationException($"The entry point {name} has too many parameters.");

                var functionName = $"wukuro_entry_{name}";
                // exported functions must be public
                glue.Append($"\n///|\npub fn {functionName}({string.Join(", ", flatParameters)}) -> Unit {{\n");
                glue.Append($"  @script.{name}({string.Join(", ", arguments)})\n}}\n");

                var package = $"{WukuroEntryPoints.PackageNamespace}:{entryName}";
                context.AddExport(functionName, $"{package}/entry#run");
                context.AddWorldExport($"{package}/entry");
                context.AddWitPackage($"{WukuroEntryPoints.PackageNamespace}-{entryName}",
                    $"package {package};\n\ninterface entry {{\n" +
                    "    use wukuro:core/types.{context, action, object};\n\n" +
                    $"    run: func({string.Join(", ", witParameters)});\n}}\n");
            }

            if (entryNames.Count == 0) return;

            context.AddImport(CoreTypesPackage, "wukuro_types");
            context.AddImport(LibraryPackage, "wukuro");
            context.AddSource("wukuro_entries.mbt", glue.ToString());
            if (objectTypes.Length > 0)
                context.AddCustomSection(WukuroEntryPoints.ObjectTypesSection,
                    Encoding.UTF8.GetBytes(objectTypes.ToString()));
        }

        /// <summary>
        ///     Returns the expression that lifts the flat values to the parameter, or null if the type is not supported.
        /// </summary>
        private static string? MapParameter(ResolvedType type, List<string> flatParameters, out string witType,
            out string? objectType, IReadOnlyList<string> sourceDirectories)
        {
            objectType = null;
            witType = "";

            string Flat(string flatType)
            {
                var name = $"p{flatParameters.Count}";
                flatParameters.Add($"{name} : {flatType}");
                return name;
            }

            if (type.Package is LibraryPackage or CoreTypesPackage)
            {
                switch (type.Name)
                {
                    case "Context":
                        witType = "borrow<context>";
                        return $"@wukuro_types.Context({Flat("Int")})";
                    case "Action":
                        witType = "borrow<action>";
                        return $"@wukuro_types.Action({Flat("Int")})";
                    case "Object":
                        witType = "borrow<object>";
                        return $"@wukuro_types.Object({Flat("Int")})";
                }
            }

            if (type.Package == LibraryPackage && type.Name == "ObjectOf" && type.Argument != null)
            {
                witType = "borrow<object>";
                objectType = FindObjectType(type.Argument.Name, sourceDirectories) ??
                             throw new InvalidOperationException(
                                 $"The marker type {type.Argument.Name} of ObjectOf has no attribute #wukuro.object_type(\"<C# type name>\").");
                return $"@wukuro.ObjectOf::from_object(@wukuro_types.Object({Flat("Int")}))";
            }

            if (type.Package != null) return null;

            switch (type.Name)
            {
                case "Bool":
                    witType = "bool";
                    return $"{Flat("Int")} != 0";
                case "Byte":
                    witType = "u8";
                    return $"{Flat("Int")}.to_byte()";
                case "Int":
                case "Int32":
                    witType = "s32";
                    return Flat("Int");
                case "UInt":
                case "UInt32":
                    witType = "u32";
                    return $"{Flat("Int")}.reinterpret_as_uint()";
                case "Int64":
                    witType = "s64";
                    return Flat("Int64");
                case "UInt64":
                    witType = "u64";
                    return $"{Flat("Int64")}.reinterpret_as_uint64()";
                case "Float":
                    witType = "f32";
                    return Flat("Float");
                case "Double":
                    witType = "f64";
                    return Flat("Double");
                case "Char":
                    witType = "char";
                    return $"Int::unsafe_to_char({Flat("Int")})";
                case "String":
                    witType = "string";
                    var pointer = Flat("Int");
                    var length = Flat("Int");
                    return $"waas_ptr2str({pointer}, {length})";
            }

            return null;
        }

        /// <summary>
        ///     Finds the C# type name of a marker type declared as <c>#wukuro.object_type("...") pub struct Name</c>.
        /// </summary>
        private static string? FindObjectType(string name, IReadOnlyList<string> sourceDirectories)
        {
            var regex = new Regex(
                @"#wukuro\.object_type\(\s*""(?<type>[^""]+)""\s*\)[^\n]*\n(?:[ \t]*(?:#|///)[^\n]*\n)*[ \t]*pub(?:\([a-z]+\))?\s+struct\s+" +
                Regex.Escape(name) + @"\b");
            foreach (var directory in sourceDirectories)
            {
                if (!Directory.Exists(directory)) continue;
                foreach (var file in Directory.GetFiles(directory, "*.mbt", SearchOption.AllDirectories))
                {
                    if (file.Replace('\\', '/').Contains("/_build/")) continue;
                    var match = regex.Match(File.ReadAllText(file));
                    if (match.Success) return match.Groups["type"].Value;
                }
            }

            return null;
        }

        private static Dictionary<string, string> ParseImports(string scriptInterface)
        {
            var aliases = new Dictionary<string, string>();
            var start = scriptInterface.IndexOf("import {", StringComparison.Ordinal);
            if (start < 0) return aliases;
            var end = scriptInterface.IndexOf('}', start);
            var block = scriptInterface.Substring(start + "import {".Length, end - start - "import {".Length);
            foreach (Match import in InterfaceImportRegex.Matches(block))
            {
                var path = import.Groups["path"].Value;
                var alias = import.Groups["alias"].Success
                    ? import.Groups["alias"].Value
                    : path.Substring(path.LastIndexOf('/') + 1);
                aliases[alias] = path;
            }

            return aliases;
        }

        /// <summary>
        ///     Resolves a type of the public interface such as <c>@alias.Name[Argument]</c>.
        /// </summary>
        private static ResolvedType ResolveType(string text, IReadOnlyDictionary<string, string> aliases)
        {
            text = text.Trim();
            string? argument = null;
            var bracket = text.IndexOf('[');
            if (bracket >= 0 && text.EndsWith("]"))
            {
                argument = text.Substring(bracket + 1, text.Length - bracket - 2);
                text = text.Substring(0, bracket);
            }

            string? package = null;
            var name = text;
            if (text.StartsWith("@"))
            {
                var dot = text.IndexOf('.');
                var alias = text.Substring(1, dot - 1);
                name = text.Substring(dot + 1);
                package = aliases.TryGetValue(alias, out var path) ? path : alias;
            }

            return new ResolvedType(package, name, argument != null ? ResolveType(argument, aliases) : null);
        }

        private static IEnumerable<string> SplitTopLevel(string text)
        {
            var depth = 0;
            var start = 0;
            for (var i = 0; i < text.Length; i++)
                switch (text[i])
                {
                    case '[' or '(':
                        depth++;
                        break;
                    case ']' or ')':
                        depth--;
                        break;
                    case ',' when depth == 0:
                        if (text.Substring(start, i - start).Trim().Length > 0)
                            yield return text.Substring(start, i - start).Trim();
                        start = i + 1;
                        break;
                }

            if (text.Substring(start).Trim().Length > 0) yield return text.Substring(start).Trim();
        }

        private static string ToKebabCase(string name)
        {
            return name.Trim('_').Replace('_', '-');
        }

        private sealed class ResolvedType
        {
            public ResolvedType(string? package, string name, ResolvedType? argument)
            {
                Package = package;
                Name = name;
                Argument = argument;
            }

            public string? Package { get; }
            public string Name { get; }
            public ResolvedType? Argument { get; }
        }
    }
}
