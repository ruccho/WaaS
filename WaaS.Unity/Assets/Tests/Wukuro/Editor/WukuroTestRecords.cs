using System;
using System.IO;
using System.Threading.Tasks;
using UnityEditor;
using UnityEngine;
using WaaS.ComponentModel.Binding;
using WaaS.ComponentModel.Runtime;
using WaaS.Unity.Editor.Wit;
using Wukuro.Editor;

namespace Wukuro.Tests
{
    // Records passed to the entry points of the test scripts and forwarded to the host function.
    // The WIT and the bindings for the scripts are generated into WukuroTestRecords at the root of the project by WukuroTestRecords.Export.

    [ComponentInterface(@"wukuro-tests:records/types")]
    public partial interface ITestRecordTypes
    {
        [ComponentRecord]
        [Serializable]
        public partial struct DoorSettings
        {
            [ComponentField] public int Count;
            [ComponentField] public string Label;
            [ComponentField] public DoorKind Kind;
            [ComponentField] public bool Locked;
            [ComponentField] public ObjectOf<Transform> Target;
            [ComponentField] public Limits Limits;
        }

        [ComponentRecord]
        [Serializable]
        public partial struct Limits
        {
            [ComponentField] public float Min;
            [ComponentField] public float Max;
        }

        public enum DoorKind
        {
            Wooden,
            Iron
        }
    }

    [ComponentInterface(@"wukuro-tests:records/functions")]
    public partial interface ITestRecordFunctions
    {
        [ComponentApi(@"receive-settings")]
        ValueTask ReceiveSettings(ITestRecordTypes.DoorSettings settings, ITestRecordTypes.DoorKind kind);
    }

    public static class WukuroTestRecords
    {
        public const string Directory = "WukuroTestRecords";
        public const string RustPath = Directory + "/record_types.rs";

        /// <summary>
        ///     The values received by the host function in the last call.
        /// </summary>
        public static (ITestRecordTypes.DoorSettings Settings, ITestRecordTypes.DoorKind Kind)? Received;

        public static string GenerateRust()
        {
            return WukuroArgumentTypeExporter.GenerateRust(typeof(ITestRecordTypes), "record_types",
                "// Generated by WukuroTestRecords.Export. DO NOT EDIT!\n");
        }

        public static void Register()
        {
            var types = ITestRecordTypes.CreateWaaSInstance(new Types());
            var functions = ITestRecordFunctions.CreateWaaSInstance(new Functions());
            WukuroRunner.RegisterImportProvider(
                new DelegateImportProvider<ISortedExportable>("wukuro-tests:records/types", () => types));
            WukuroRunner.RegisterImportProvider(
                new DelegateImportProvider<ISortedExportable>("wukuro-tests:records/functions", () => functions));
        }

        /// <summary>
        ///     Generates the WIT, the MoonBit bindings and the Rust macros of the records, and reimports the test scripts.
        ///     Run with <c>unity run WaaS.Unity -- -executeMethod Wukuro.Tests.WukuroTestRecords.Export</c>.
        /// </summary>
        public static void Export()
        {
            var exitCode = 0;
            try
            {
                WitExporter.ExportAll(true);
                File.WriteAllText(RustPath, GenerateRust());
                foreach (var path in new[]
                         {
                             "Assets/Tests/Wukuro/wukuro-tests.rs", "Assets/Tests/Wukuro/wukuro-tests.mbt",
                             "Assets/Tests/Wukuro/MoonBitPackage/moon.pkg"
                         })
                    AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceUpdate);
            }
            catch (Exception ex)
            {
                Debug.LogException(ex);
                exitCode = 1;
            }

            if (Application.isBatchMode) EditorApplication.Exit(exitCode);
        }

        private class Types : ITestRecordTypes
        {
            public Core.ITypes.IObjectResourceImpl Object => WukuroObjects.ResourceType;
        }

        private class Functions : ITestRecordFunctions
        {
            public Core.ITypes.IObjectResourceImpl Object => WukuroObjects.ResourceType;

            public ValueTask ReceiveSettings(ITestRecordTypes.DoorSettings settings, ITestRecordTypes.DoorKind kind)
            {
                Received = (settings, kind);
                return default;
            }
        }
    }
}
